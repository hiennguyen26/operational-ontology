def drop_claude_only(text: str, where: str = "") -> str:
    """``text`` without the lines from each ``<!-- claude-only -->`` line to its ``<!-- /claude-only -->`` line (both
    included); the blank lines around a dropped block fold into one. An unclosed or stray marker is refused."""
    out: List[str] = []
    inside = False
    for line in text.split("\n"):
        mark = line.strip()
        if mark == CLAUDE_ONLY:
            if inside:
                raise RenderError("%s: %s inside another claude-only block" % (where, CLAUDE_ONLY))
            inside = True
            continue
        if mark == CLAUDE_ONLY_END:
            if not inside:
                raise RenderError("%s: %s without its %s" % (where, CLAUDE_ONLY_END, CLAUDE_ONLY))
            inside = False
            continue
        if CLAUDE_ONLY in line or CLAUDE_ONLY_END in line:
            raise RenderError("%s: a claude-only marker must stand on a line of its own" % where)
        if not inside:
            out.append(line)
    if inside:
        raise RenderError("%s: %s is never closed (%s)" % (where, CLAUDE_ONLY, CLAUDE_ONLY_END))
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out))


def cut_description(text: str, limit: int = DESCRIPTION_MAX) -> str:
    """``text`` on one line, cut after the last sentence end (``.``, ``!`` or ``?`` before a space or the end) that
    fits in ``limit`` characters; without one, after the last whole word that fits, with a period."""
    text = " ".join(str(text).split())
    if len(text) <= limit:
        return text
    best = 0
    for m in re.finditer(r"[.!?](?=\s|$)", text):
        if m.end() > limit:
            break
        best = m.end()
    if best:
        return text[:best]
    head = text[:limit].rsplit(" ", 1)[0].rstrip(",;:")
    return head[:limit - 1] + "."


def plain_scalar(value: str, where: str = "") -> str:
    """The text of a one-line YAML scalar: a "double quoted" or 'single quoted' value unquoted, a plain one as it
    is. A folded or literal block (``>``, ``|``) or a quote left open is refused, since the cut works on the text."""
    if value[:1] in (">", "|"):
        raise RenderError("%s: write the description on one line, not as a %s block" % (where, value[:1]))
    if value[:1] == '"':
        try:
            text = json.loads(value)
        except ValueError:
            text = None
        if not isinstance(text, str):
            raise RenderError("%s: the quoted description is not one closed \"...\" string" % where)
        return text
    if value[:1] == "'":
        if len(value) < 2 or not value.endswith("'") or "'" in value[1:-1].replace("''", ""):
            raise RenderError("%s: the quoted description is not one closed '...' string" % where)
        return value[1:-1].replace("''", "'")
    return value


def yaml_scalar(text: str, quoted: bool) -> str:
    """``text`` as a one-line YAML value: double quoted (JSON escapes, which YAML reads) when the source quoted it."""
    return json.dumps(text, ensure_ascii=False) if quoted else text


def split_frontmatter(text: str, where: str = "") -> Tuple[List[Tuple[str, str]], str]:
    """``([(key, value)], body)`` of a SKILL.md: ``key: value`` lines (a list item line belongs to the key above it
    and is dropped with it), then the body after the closing ``---``."""
    if not text.startswith("---\n"):
        raise RenderError("%s: a SKILL.md starts with a --- frontmatter block" % where)
    head, sep, body = text[4:].partition("\n---\n")
    if not sep:
        raise RenderError("%s: the frontmatter block is not closed" % where)
    pairs: List[Tuple[str, str]] = []
    for line in head.split("\n"):
        if not line.strip() or re.match(r"^\s+- ", line):
            continue
        m = re.match(r"^([a-z][a-z-]*):\s*(.*)$", line)
        if not m:
            raise RenderError("%s: unreadable frontmatter line %r" % (where, line))
        pairs.append((m.group(1), m.group(2).strip()))
    return pairs, body


# the span between a rewrite's first and last words: any text but a blank line, so a match stays in one paragraph
SPAN = r"(?:(?!\n[ \t]*\n)[\s\S])*?"


def neutral_body(text: str, where: str = "") -> str:
    """The body rules: the rewrites, then the plugin root as the repo path. A rewrite whose first words are there
    but whose last words are not in the same paragraph is refused: the source changed, and the rewrite would
    otherwise reach into the next paragraph or leave half a passage."""
    for first, last, instead in REWRITES:
        pattern = re.compile(_ws(first) + SPAN + _ws(last))
        text, count = pattern.subn(lambda _m: instead, text, count=1)
        if not count and re.search(_ws(first), text):
            raise RenderError("%s: the passage that starts %r no longer ends %r in the same paragraph; mark it %s "
                              "... %s in the source, or update REWRITES in ontokit/agents.py" % (
                                  where, first, last, CLAUDE_ONLY, CLAUDE_ONLY_END))
    text = text.replace(PLUGIN_ONTO, ONTO)
    return text.replace("${CLAUDE_PLUGIN_ROOT}", KIT_REL)


def header(source_rel: str) -> str:
    return "<!-- %s from %s; edit the source, then run %s -->\n" % (GENERATED, source_rel, REGENERATE)


def forbidden_in(text: str) -> List[str]:
    return [name for name, pattern in FORBIDDEN if pattern.search(text)]


def render_file(text: str, source_rel: str, skill: bool) -> str:
    """One neutral file from the source text (``skill``: a SKILL.md with frontmatter)."""
    text = drop_claude_only(text.replace("\r\n", "\n"), source_rel)
    if skill:
        pairs, body = split_frontmatter(text, source_rel)
        meta = dict(pairs)
        if not meta.get("name") or not meta.get("description"):
            raise RenderError("%s: the frontmatter needs name and description" % source_rel)
        description = yaml_scalar(cut_description(plain_scalar(meta["description"], source_rel)),
                                  meta["description"][:1] in "\"'")
        out = "---\nname: %s\ndescription: %s\n---\n%s%s" % (
            meta["name"], description, header(source_rel), neutral_body(body, source_rel))
    else:
        out = header(source_rel) + "\n" + neutral_body(text, source_rel)
    left = forbidden_in(out)
    if left:
        raise RenderError("%s: the neutral render still holds %s; mark that passage %s ... %s in the source, or add a "
                          "rewrite to ontokit/agents.py" % (source_rel, ", ".join(left), CLAUDE_ONLY, CLAUDE_ONLY_END))
    if EM_DASH in out:
        raise RenderError("%s: an em dash; use a colon, a comma or a full stop" % source_rel)
    return out


def _files_of(folder: str) -> List[str]:
    """The files under ``folder`` (relative, with /), sorted; hidden files, caches and Finder copies left out."""
    out = []
    for dirpath, dirs, files in os.walk(folder):
        dirs[:] = sorted(d for d in dirs if not d.startswith(".") and d != "__pycache__")
        for name in sorted(files):
            if name.startswith(".") or name.endswith(".pyc") or JUNK_RE.match(name):
                continue
            out.append(os.path.relpath(os.path.join(dirpath, name), folder).replace(os.sep, "/"))
    return sorted(out)


def skill_names(source: str) -> List[str]:
    if not os.path.isdir(source):
        return []
    return sorted(d for d in os.listdir(source) if os.path.isfile(os.path.join(source, d, "SKILL.md")))


def render_skills(source: str) -> Dict[str, bytes]:
    """``{path under .agents/skills: bytes}`` for every skill folder of ``source`` (``plugins/general-ontology/
    skills``): its SKILL.md and its references, Markdown rendered and any other file copied as it is."""
    out: Dict[str, bytes] = {}
    for name in skill_names(source):
        if not NAME_RE.match(name):
            raise RenderError("%s/%s: a skill name is lower case words joined by hyphens" % (SOURCE_REL, name))
        folder = os.path.join(source, name)
        for rel in _files_of(folder):
            path = os.path.join(folder, *rel.split("/"))
            with open(path, "rb") as fh:
                data = fh.read()
            key = "%s/%s" % (name, rel)
            if rel.endswith(".md"):
                text = render_file(data.decode("utf-8"), "%s/%s" % (SOURCE_REL, key), rel == "SKILL.md")
                if rel == "SKILL.md":
                    pairs, _body = split_frontmatter(text, key)
                    if dict(pairs).get("name") != name:
                        raise RenderError("%s/%s: the name in the frontmatter is not the folder name" % (
                            SOURCE_REL, key))
                data = text.encode("utf-8")
            out[key] = data
    return out


def _generated_folder(target: str, name: str) -> bool:
    """True when ``.agents/skills/<name>`` is one this render made (its SKILL.md carries the header)."""
    try:
        with open(os.path.join(target, name, "SKILL.md"), encoding="utf-8") as fh:
            return GENERATED in fh.read(4096)
    except (OSError, UnicodeDecodeError):
        return False


def skills_drift(root: str) -> Dict[str, Any]:
    """How ``<root>/.agents/skills`` differs from the render of ``<root>/plugins/general-ontology/skills``:
    ``{missing, changed, extra}`` (paths under ``.agents/skills``), with ``source`` False when there is no source.
    Only the kit's own skill folders count: one the user added there is never touched or reported."""
    source = os.path.join(root, *SOURCE_REL.split("/"))
    target = os.path.join(root, *TARGET_REL.split("/"))
    if not skill_names(source):
        return {"source": False, "missing": [], "changed": [], "extra": [], "files": 0}
    want = render_skills(source)
    owned = set(n.split("/", 1)[0] for n in want)
    if os.path.isdir(target):
        owned |= {d for d in os.listdir(target) if os.path.isdir(os.path.join(target, d)) and
                  _generated_folder(target, d)}
    have: Dict[str, bytes] = {}
    for name in sorted(owned):
        folder = os.path.join(target, name)
        if not os.path.isdir(folder):
            continue
        for rel in _files_of(folder):
            with open(os.path.join(folder, *rel.split("/")), "rb") as fh:
                have["%s/%s" % (name, rel)] = fh.read()
    return {"source": True, "files": len(want),
            "missing": sorted(k for k in want if k not in have),
            "changed": sorted(k for k in want if k in have and have[k] != want[k]),
            "extra": sorted(k for k in have if k not in want)}


def write_skills(root: str) -> Dict[str, Any]:
    """Write the render into ``<root>/.agents/skills``: changed and missing files written, the kit's stale files
    removed (and their folders, once empty). Returns ``{written, removed, unchanged}``."""
    drift = skills_drift(root)
    if not drift["source"]:
        raise UsageError("onto agents render: no skills at %s/%s (run it in a template checkout or a topic that "
                         "carries its kit)" % (root, SOURCE_REL))
    from . import store

    want = render_skills(os.path.join(root, *SOURCE_REL.split("/")))
    target = os.path.join(root, *TARGET_REL.split("/"))
    written = sorted(drift["missing"] + drift["changed"])
    for rel in written:
        path = os.path.join(target, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        store.write_bytes(path, want[rel])
    for rel in drift["extra"]:
        path = os.path.join(target, *rel.split("/"))
        os.remove(path)
        parent = os.path.dirname(path)
        while parent != target and os.path.isdir(parent) and not os.listdir(parent):
            os.rmdir(parent)
            parent = os.path.dirname(parent)
    return {"written": written, "removed": list(drift["extra"]), "unchanged": len(want) - len(written)}


