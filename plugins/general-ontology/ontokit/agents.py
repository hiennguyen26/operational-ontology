"""Agent harnesses: the neutral skills render and the per-harness wiring (``onto agents``, ``onto setup --agent``).

**The neutral skills.** ``plugins/general-ontology/skills/`` stays the one source. ``render_skills`` turns it into
``.agents/skills/<name>/SKILL.md`` plus ``references/`` at the template root, which Devin, Codex, Cursor, GitHub
Copilot and Gemini CLI read (Claude Code keeps the plugin's own copy; ``.claude/skills/`` is never written, since
several harnesses read both folders and would load every skill twice). The render rules, in order:

- paragraphs between ``<!-- claude-only -->`` and ``<!-- /claude-only -->`` lines are dropped (the markers are HTML
  comments, so the Claude render never shows them);
- the frontmatter keeps only ``name`` and ``description``, and the description is cut at the last sentence end
  within ``DESCRIPTION_MAX`` characters;
- the sentence that defines ``O`` becomes ``O_SENTENCE``, and every other plugin-root path becomes the repo path;
- ``REWRITES`` turn the Claude Code only passages of today's sources (the question tool, the plugin install) into
  their plain-text form; a passage a later source marks ``claude-only`` is simply gone, and the rewrite then finds
  nothing to do;
- a header comment says the file is generated, from which source, and how to regenerate it.

A render that still holds a ``FORBIDDEN`` token is refused (``RenderError``), so a new Claude-only line in a source
fails ``onto agents render`` and the sync test instead of reaching another harness.

**The wiring.** ``HARNESSES`` lists what each harness reads, the files a topic gets for it (``files``) and the parts
set up in the harness's own app (``paste``). Every file is repo-relative and holds no absolute path or user name.
``plan_file`` merges a file into what is on disk: a JSON file keeps every other key (only the ``onto`` entries are
the kit's), a TOML file keeps every other table, and a file the user changed is never overwritten (``refused``),
unless its bytes are the ones setup itself wrote earlier. Deterministic: same input, same bytes.
"""

