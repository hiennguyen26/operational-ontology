def _root(ctx: Context) -> Tuple[str, str]:
    from . import doctor

    start = os.path.abspath(os.path.expanduser(ctx.explicit or ctx.cwd or os.getcwd()))
    return doctor.locate(start, ctx.env, ctx.explicit)


def _quiet_stamp(ctx: Context, where: str, root: str) -> None:
    """The version line names the folder these results are about, never a topic ``$ONTO_REPO`` points at."""
    from . import store
    from .errors import OntoError

    ctx.env.pop("ONTO_REPO", None)
    found = None
    if where == "topic":
        try:
            found = store.Repo.open(root)
        except OntoError:
            found = None
    ctx.repo = found
    if found is None:
        ctx.explicit, ctx.cwd = None, os.path.abspath(os.sep)


def show(name: str) -> Dict[str, Any]:
    h = harness(name)
    return {"agent": h["name"], "label": h["label"], "reads": list(h["reads"]),
            "files": [{"path": f["path"], "content": fresh(f).decode("utf-8")} for f in h["files"]],
            "paste": paste_blocks([h["name"]]), "open": h["open"], "notes": list(h["notes"])}


def cmd_agents(ctx: Context, args: Dict[str, Any]) -> Dict[str, Any]:
    action = args.get("action") or "list"
    if action == "show":
        if not args.get("name"):
            raise UsageError("onto agents show needs a name: one of %s" % ", ".join(NAMES), accepted=list(NAMES))
        result = {"action": "show"}
        result.update(show(args["name"]))
        where, root = _root(ctx)
        _quiet_stamp(ctx, where, root)
        return result
    if args.get("name"):
        raise UsageError("onto agents %s takes no name (only show does)" % action)
    where, root = _root(ctx)
    _quiet_stamp(ctx, where, root)
    if action == "list":
        rows = []
        for h in HARNESSES:
            rows.append({"name": h["name"], "label": h["label"], "reads": list(h["reads"]),
                         "files": [f["path"] for f in h["files"]], "paste": bool(h["paste"]),
                         "wired": wired(root, h["name"]) if where in ("topic", "template") else "not checked"})
        return {"action": "list", "where": where, "root": root, "agents": rows}
    if action != "render":
        raise UsageError("onto agents: list, show <name> or render [--check]")
    if where not in ("topic", "template"):
        raise UsageError("onto agents render: run it in a template checkout (or a topic that carries its kit): %s is "
                         "neither" % root)
    if args.get("check"):
        drift = skills_drift(root)
        if not drift["source"]:
            raise UsageError("onto agents render --check: no skills at %s/%s" % (root, SOURCE_REL))
        bad = drift["missing"] + drift["changed"] + drift["extra"]
        return {"action": "render", "check": True, "root": root, "files": drift["files"],
                "missing": drift["missing"], "changed": drift["changed"], "extra": drift["extra"],
                "exit_code": 1 if bad else 0}
    done = write_skills(root)
    result = {"action": "render", "check": False, "root": root}
    result.update(done)
    return result


def render_agents(result: Dict[str, Any], mode: str, ctx: Context) -> List[str]:
    from .onboard import one_line

    action = result.get("action")
    if action == "list":
        lines = ["agents at %s (%s)" % (one_line(result.get("root")), result.get("where"))]
        for row in result.get("agents") or []:
            lines.append("%-8s %-15s %s" % (row["name"], row["wired"], row["label"]))
            lines.append("         reads: %s" % "; ".join(row["reads"]))
            if row["files"]:
                lines.append("         files: %s" % ", ".join(row["files"]))
        lines.append("Details: onto agents show <name>; wire one: onto setup --agent <name>")
        return lines
    if action == "show":
        lines = ["%s (%s)" % (result.get("label"), result.get("agent")), "Reads:"]
        lines += ["  %s" % r for r in result.get("reads") or []]
        for f in result.get("files") or []:
            lines.append("File %s:" % f["path"])
            lines += ["  %s" % line for line in f["content"].rstrip("\n").split("\n")]
        if not result.get("files"):
            lines.append("Files: none")
        for block in result.get("paste") or []:
            lines.append("Paste, %s:" % block["title"])
            lines += ["  %s" % line for line in block["text"].split("\n")]
        lines.append("Open: %s" % result.get("open"))
        lines += ["Note: %s" % n for n in result.get("notes") or []]
        return lines
    if result.get("check"):
        bad = [("missing", result.get("missing") or []), ("changed", result.get("changed") or []),
               ("not in the render", result.get("extra") or [])]
        if not any(paths for _what, paths in bad):
            return [".agents/skills matches the render (%d files)" % (result.get("files") or 0)]
        lines = [".agents/skills differs from the render of %s:" % SOURCE_REL]
        for what, paths in bad:
            lines += ["  %s: %s" % (what, p) for p in paths]
        lines.append("Regenerate it: %s" % REGENERATE)
        return lines
    written, removed = result.get("written") or [], result.get("removed") or []
    lines = [".agents/skills: %d written, %d removed, %d unchanged" % (
        len(written), len(removed), result.get("unchanged") or 0)]
    lines += ["  wrote %s" % p for p in written] + ["  removed %s" % p for p in removed]
    return lines
