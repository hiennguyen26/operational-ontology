def _key(path: Sequence[str], value: Any) -> Dict[str, Any]:
    return {"kind": "key", "path": list(path), "value": value}


def _member(path: Sequence[str], value: Any, marker: str) -> Dict[str, Any]:
    return {"kind": "member", "path": list(path), "value": value, "marker": marker}


def _hook_group(matcher: str, command: str, timeout: Optional[int] = None) -> Dict[str, Any]:
    hook: Dict[str, Any] = {"type": "command", "command": command}
    if timeout is not None:
        hook["timeout"] = timeout
    return {"matcher": matcher, "hooks": [hook]}


