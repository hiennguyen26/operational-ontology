WIRED_PATHS = tuple(sorted(f["path"] for h in HARNESSES for f in h["files"]))


def harness(name: str) -> Dict[str, Any]:
    found = _BY_NAME.get(str(name or "").strip().lower())
    if found is None:
        raise UsageError("unknown agent %r; one of %s" % (name, ", ".join(NAMES)), accepted=list(NAMES))
    return found


def parse_agents(value: Any) -> List[str]:
    """A list of harness names (``claude,devin`` or a list), checked, without repeats, in ``NAMES`` order."""
    items: List[str] = []
    for item in (value if isinstance(value, (list, tuple)) else [value]):
        items.extend(p.strip().lower() for p in str(item or "").split(",") if p.strip())
    unknown = sorted({i for i in items if i not in _BY_NAME})
    if unknown:
        raise UsageError("--agent: unknown agent %s; one of %s" % (", ".join(unknown), ", ".join(NAMES)))
    return [n for n in NAMES if n in items]


# merging one file -----------------------------------------------------------------------------------------------
def _dump_json(doc: Any) -> bytes:
    return (json.dumps(doc, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _container(doc: Dict[str, Any], path: List[str], create: bool) -> Tuple[Optional[Dict[str, Any]], str]:
    """The object holding ``path[-1]`` (made on the way when ``create``), or (None, why)."""
    node: Any = doc
    for i, key in enumerate(path[:-1]):
        child = node.get(key)
        if child is None:
            if not create:
                return None, ""
            child = node[key] = {}
        if not isinstance(child, dict):
            return None, "%s is not an object" % ".".join(path[:i + 1])
        node = child
    return node, ""


def _merge_json(spec: Dict[str, Any], current: Optional[bytes], own: bool) -> Tuple[str, Optional[bytes], str]:
    if current is None:
        doc: Dict[str, Any] = {}
    else:
        try:
            doc = json.loads(current.decode("utf-8"))
        except (ValueError, UnicodeDecodeError) as exc:
            return "refused", None, "it is not valid JSON (%s)" % exc
        if not isinstance(doc, dict):
            return "refused", None, "it is not a JSON object"
    changed = False
    for part in spec["parts"]:
        path, value = part["path"], json.loads(json.dumps(part["value"]))  # a copy: the spec stays as it is
        node, why = _container(doc, path, True)
        if node is None:
            return "refused", None, why
        last = path[-1]
        if part["kind"] == "key":
            if last in node and node[last] == value:
                continue
            if last in node and not own:
                return "refused", None, "%s holds another entry" % ".".join(path)
            node[last] = value
            changed = True
            continue
        have = node.get(last)
        if have is None:
            items: List[Any] = []
        elif isinstance(have, list):
            items = list(have)
        elif isinstance(have, str):
            items = [have]
        else:
            return "refused", None, "%s is not a list" % ".".join(path)
        if value in items:
            continue
        ours = [i for i, item in enumerate(items) if part["marker"] in json.dumps(item, ensure_ascii=False)]
        if ours and not own:
            return "refused", None, "%s holds another onto entry" % ".".join(path)
        for i in reversed(ours):
            del items[i]
        items.append(value)
        node[last] = items
        changed = True
    if not changed:
        return "already", current, ""
    return "write", _dump_json(doc), ""


TABLE_RE = re.compile(r"^\s*\[\[?[^\]\n]+\]\]?\s*(#.*)?$")


def _toml_key(key: str) -> str:
    """A regex for one bare TOML key part as written bare, "double quoted" or 'single quoted'."""
    k = re.escape(key)
    return r"(?:%s|\"%s\"|'%s')" % (k, k, k)


def _merge_toml(spec: Dict[str, Any], current: Optional[bytes], own: bool) -> Tuple[str, Optional[bytes], str]:
    block = spec["text"]
    if current is None:
        return "write", block.encode("utf-8"), ""
    try:
        text = current.decode("utf-8")
    except UnicodeDecodeError:
        return "refused", None, "it is not UTF-8 text"
    lines = text.split("\n")
    parts = spec["table"].split(".")
    head = re.compile(r"^\s*\[\s*%s\s*\]\s*(#.*)?$" % r"\s*\.\s*".join(_toml_key(k) for k in parts))
    start = next((i for i, line in enumerate(lines) if head.match(line)), None)
    if start is None:
        top = _toml_key(parts[0])
        if re.search(r"(?m)^\s*\[\s*%s\s*\]" % top, text) or re.search(r"(?m)^\s*%s\s*[.=]" % top, text):
            return "refused", None, "it sets %s another way; add the [%s] table by hand" % (parts[0], spec["table"])
        if not text.strip():
            return "write", block.encode("utf-8"), ""
        body = text.rstrip("\n") + "\n\n"  # one blank line between the user's tables and the kit's
        return "write", (body + block).encode("utf-8"), ""
    end = next((i for i in range(start + 1, len(lines)) if TABLE_RE.match(lines[i])), len(lines))
    # the table's body, not its header line: [mcp_servers."onto"] is the same table as [mcp_servers.onto]
    have = "\n".join(lines[start + 1:end]).strip()
    if have == block.strip().split("\n", 1)[1].strip():
        return "already", current, ""
    if not own:
        return "refused", None, "its [%s] table differs" % spec["table"]
    rest = lines[end:]
    new = "\n".join(lines[:start] + block.rstrip("\n").split("\n") + ([""] + rest if rest else [""]))
    return "write", new.encode("utf-8"), ""


def plan_file(spec: Dict[str, Any], current: Optional[bytes], own: bool = False) -> Tuple[str, Optional[bytes], str]:
    """(``already`` | ``write`` | ``refused``, the bytes to write or keep, why refused) for one harness file over
    ``current`` (None when absent). ``own``: these bytes are the ones setup wrote earlier, so the kit's parts may
    change; otherwise a file whose kit part differs is the user's and is refused."""
    fmt = spec["format"]
    if fmt == "json":
        return _merge_json(spec, current, own)
    if fmt == "toml":
        return _merge_toml(spec, current, own)
    data = spec["text"].encode("utf-8")
    if current is None or (own and current != data):
        return "write", data, ""
    if current == data:
        return "already", current, ""
    return "refused", None, "it differs from the kit's"


def fresh(spec: Dict[str, Any]) -> bytes:
    """The bytes of ``spec`` written into an empty repo."""
    _status, data, _why = plan_file(spec, None)
    assert data is not None
    return data


def _read(root: str, rel: str) -> Optional[bytes]:
    path = os.path.join(root, *rel.split("/"))
    if not os.path.isfile(path):
        return None
    try:
        with open(path, "rb") as fh:
            return fh.read()
    except OSError:
        return None


def file_states(root: str, name: str) -> List[Dict[str, str]]:
    """``[{path, state}]`` for each file of harness ``name`` in ``root``: ``absent``, ``ok`` (the kit's parts are
    there, as rendered) or ``differs`` (missing or different kit parts, or unreadable)."""
    out = []
    for spec in harness(name)["files"]:
        current = _read(root, spec["path"])
        if current is None:
            out.append({"path": spec["path"], "state": "absent"})
            continue
        status, _data, _why = plan_file(spec, current)
        out.append({"path": spec["path"], "state": "ok" if status == "already" else "differs"})
    return out


def wired(root: str, name: str) -> str:
    """``wired``, ``partly``, ``differs``, ``not wired`` or ``no files`` for harness ``name`` in ``root``."""
    if name == "claude":
        from . import doctor

        wiring = doctor.settings_wiring(root)
        return "wired" if (wiring.get("project") or wiring.get("local")) else "not wired"
    states = [s["state"] for s in file_states(root, name)]
    if not states:
        return "no files"
    if all(s == "absent" for s in states):
        return "not wired"
    if "differs" in states:
        return "differs"
    return "wired" if all(s == "ok" for s in states) else "partly"


def apply(root: str, name: str, own: Dict[str, str]) -> List[Dict[str, Any]]:
    """Write the files of harness ``name`` into ``root``. ``own`` maps a path to the sha256 of the bytes setup wrote
    there earlier. Returns ``[{path, status (done | already | refused), detail, sha}]``."""
    from . import store

    out = []
    for spec in harness(name)["files"]:
        rel = spec["path"]
        current = _read(root, rel)
        mine = current is not None and own.get(rel) == util.sha256_hex(current)
        status, data, why = plan_file(spec, current, mine)
        item: Dict[str, Any] = {"path": rel, "status": status, "detail": why, "sha": None}
        if status == "write" and data is not None:
            path = os.path.join(root, *rel.split("/"))
            os.makedirs(os.path.dirname(path), exist_ok=True)
            store.write_bytes(path, data)
            item["status"], item["sha"] = "done", util.sha256_hex(data)
        elif status == "already" and current is not None:
            item["sha"] = util.sha256_hex(current)
        out.append(item)
    return out


def paste_blocks(names: Sequence[str]) -> List[Dict[str, str]]:
    return [{"agent": n, "title": block["title"], "text": block["text"]} for n in names
            for block in harness(n)["paste"]]


def skills_check(root: str) -> Dict[str, Any]:
    """The doctor's ``agents`` check: ``.agents/skills`` equals the render of this kit's skills, and every wired
    harness file holds the kit's parts as rendered."""
    from .doctor import check

    problems: List[str] = []
    fixes: List[str] = []
    try:
        drift = skills_drift(root)
    except (RenderError, OSError, UnicodeDecodeError) as exc:
        drift = {"source": True, "missing": [], "changed": [], "extra": [], "error": str(exc)}
    if drift.get("error"):
        problems.append("the skills do not render: %s" % drift["error"])
    elif drift["source"]:
        bad = drift["missing"] + drift["changed"] + drift["extra"]
        if bad:
            shown = ", ".join(bad[:3]) + (", ..." if len(bad) > 3 else "")
            problems.append(".agents/skills differs from the render of kit %s (%d file%s: %s)" % (
                __version__, len(bad), "" if len(bad) == 1 else "s", shown))
            fixes.append("in the template, run %s and commit it; in a topic, take .agents/ from the kit "
                         "(git checkout kit/general-ontology -- .agents)" % REGENERATE)
    names = []
    for h in HARNESSES:
        if not h["files"]:
            continue
        state = wired(root, h["name"])
        if state in ("wired",):
            names.append(h["name"])
        elif state in ("differs", "partly"):
            names.append(h["name"])
            states = file_states(root, h["name"])
            odd = [s["path"] for s in states if s["state"] != "ok"]
            changed = [s["path"] for s in states if s["state"] == "differs"]
            problems.append("%s: %s %s its render" % (h["name"], ", ".join(odd), "differ from" if len(odd) > 1
                                                      else "differs from"))
            if changed:
                # setup never overwrites a file it did not write, so it cannot repair these: name the real repair
                fixes.append("merge the kit's entries into %s by hand (onto agents show %s prints them), or move "
                             "%s aside and run onto setup --agent %s" % (
                                 ", ".join(changed), h["name"], "them" if len(changed) > 1 else "it", h["name"]))
            else:
                fixes.append("onto setup --agent %s" % h["name"])
    if problems:
        return check("agents", "warn", "; ".join(problems), "; ".join(fixes))
    parts = [".agents/skills matches the render of kit %s" % __version__ if drift["source"] else
             "no skills to render in this kit"]
    parts.append("wired: %s" % ", ".join(names) if names else "no agent files")
    return check("agents", "ok", "; ".join(parts))


